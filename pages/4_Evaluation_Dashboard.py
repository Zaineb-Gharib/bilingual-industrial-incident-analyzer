"""Real persisted evaluation metrics dashboard."""

import json

import pandas as pd
import plotly.express as px
import streamlit as st

from src.storage.repositories import AnalysisRepository
from src.ui import configure_page, root_settings

configure_page("Evaluation Dashboard")
st.title("Evaluation dashboard")
st.caption("Only persisted run data · explicit denominators · no placeholder metrics")

settings = root_settings()
repository = AnalysisRepository(settings.database_path)
runs = repository.list_runs()
if not runs:
    st.info("No evaluation run exists yet. Prepare and run a batch first.")
    st.stop()

labels = {}
for run in runs:
    manifest = json.loads(run["manifest_json"])
    labels[f"{run['run_id']} · {manifest['provider']} · {run['status']}"] = run
selected = st.selectbox("Run", list(labels))
run = labels[selected]
manifest = json.loads(run["manifest_json"])

if manifest["provider"] == "demo":
    st.markdown(
        '<div class="demo-band">DEMO METRICS — generated by the deterministic rule engine. These are pipeline checks, not LLM performance claims.</div>',
        unsafe_allow_html=True,
    )

m1, m2, m3, m4 = st.columns(4)
m1.metric("Status", run["status"])
m2.metric("Completed outputs", run["completed_tasks"])
m3.metric("Provider", manifest["provider"])
m4.metric("Model", manifest["model"])

metrics = repository.list_metrics(run["run_id"])
if not metrics:
    st.warning("This run has no final metrics yet; resume it from Batch Evaluation.")
    st.stop()

rows = [
    {
        "metric": item.metric_name,
        "value": item.value,
        "numerator": item.numerator,
        "denominator": item.denominator,
        "exclusions": item.exclusions,
        "source": item.source,
        "group": ", ".join(f"{key}={value}" for key, value in item.group.items()) or "overall",
    }
    for item in metrics
]
frame = pd.DataFrame(rows)
overall = frame[frame["group"] == "overall"].copy()

headline_names = [
    "category_success_end_to_end",
    "severity_success_end_to_end",
    "first_pass_json_validity_rate",
    "evidence_grounding_rate",
]
headline = overall[overall["metric"].isin(headline_names)]
columns = st.columns(max(1, len(headline)))
for column, (_, item) in zip(columns, headline.iterrows(), strict=False):
    value = "N/A" if pd.isna(item["value"]) else f"{item['value']:.1%}"
    column.metric(item["metric"].replace("_", " ").title(), value)

rate_rows = overall[
    overall["metric"].isin(
        [
            "category_success_end_to_end",
            "severity_success_end_to_end",
            "responsible_team_exact_match",
            "first_pass_json_validity_rate",
            "repair_assisted_validity_rate",
            "evidence_grounding_rate",
            "bilingual_consistency_score",
        ]
    )
]
if not rate_rows.empty:
    chart = px.bar(
        rate_rows,
        x="value",
        y="metric",
        orientation="h",
        range_x=[0, 1],
        title="Overall automatic metrics",
        labels={"value": "Rate / score", "metric": "Metric"},
    )
    st.plotly_chart(chart, use_container_width=True)

st.subheader("All metrics and denominators")
group_options = ["overall", *sorted(set(frame["group"]) - {"overall"})]
group = st.selectbox("Breakdown", group_options)
st.dataframe(
    frame[frame["group"] == group],
    use_container_width=True,
    hide_index=True,
    column_config={"value": st.column_config.NumberColumn(format="%.4f")},
)
st.download_button(
    "Download displayed metrics CSV",
    data=frame[frame["group"] == group].to_csv(index=False).encode("utf-8-sig"),
    file_name=f"{run['run_id']}_{group.replace('=', '-')}_metrics.csv",
    mime="text/csv",
)
st.caption(
    "Automatic metrics use versioned deterministic formulas. Human rubric scores and translation approvals "
    "remain unavailable until independent reviewers complete them."
)
